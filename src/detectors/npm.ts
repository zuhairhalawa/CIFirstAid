import { patternRule } from './rule.js';

// npm <= 6 prints "npm ERR!", npm >= 7 prints "npm error". Both are covered.
const NPM = '^npm (?:ERR!|error) ';
const re = (s: string) => new RegExp(s);

export const npmRules = [
  patternRule({
    id: 'npm-lockfile-out-of-sync',
    category: 'npm',
    score: 92,
    patterns: [
      /can only install packages when your package\.json and package-lock\.json(?: or npm-shrinkwrap\.json)? are in sync/,
      /^npm (?:ERR!|error) (?:Missing|Invalid): .+ from lock file/,
    ],
    title: 'npm ci failed: package.json and package-lock.json are out of sync',
    explanation:
      '"npm ci" refuses to run when the lockfile does not match package.json. The lines below name the packages that differ.',
    suggestions: [
      'Run "npm install" locally with the same npm major version as CI, then commit the updated package-lock.json.',
      'Make sure the lockfile was generated by a compatible npm version (lockfileVersion) and not edited by hand.',
    ],
    after: 4,
    maxEvidence: 4,
  }),
  patternRule({
    id: 'npm-eresolve',
    category: 'npm',
    score: 88,
    patterns: [re(NPM + 'code ERESOLVE'), re(NPM + 'ERESOLVE'), /Could not resolve dependency:/],
    title: 'npm cannot resolve conflicting (peer) dependencies (ERESOLVE)',
    explanation:
      'Two packages require incompatible versions of a shared dependency, usually a peer dependency. The "Found:" and "Could not resolve dependency:" lines show the conflict.',
    suggestions: [
      'Upgrade or align the conflicting packages named in the "Found:" / "peer" lines.',
      'Only as a last resort add --legacy-peer-deps (or set legacy-peer-deps=true in .npmrc); it hides the conflict rather than fixing it.',
    ],
    after: 6,
    maxEvidence: 3,
  }),
  patternRule({
    id: 'npm-etarget',
    category: 'npm',
    score: 88,
    patterns: [re(NPM + 'notarget No matching version found for ([^ ]+)'), re(NPM + 'code ETARGET')],
    title: (m) => 'npm: no matching version' + (m[1] ? ' for ' + m[1] : ''),
    explanation: 'The version (or range) requested does not exist in the registry, or has been unpublished.',
    suggestions: ['Check the package name and version on the registry (npm view <pkg> versions).', 'If it is a private package, make sure the registry/auth is configured in the job.'],
    after: 1,
  }),
  patternRule({
    id: 'npm-404',
    category: 'npm',
    score: 80,
    patterns: [re(NPM + '404 +(?:Not Found - GET )?([^ ]+)'), re(NPM + 'code E404')],
    title: (m) => 'npm package not found (404)' + (m[1] && m[1] !== 'Not' ? ': ' + m[1] : ''),
    explanation:
      'The registry returned 404. Either the package does not exist, the name is misspelled, or it is private and the job is not authenticated.',
    suggestions: ['Check the package name.', 'For private packages configure an auth token (e.g. NODE_AUTH_TOKEN with actions/setup-node registry-url) for the job.'],
    after: 2,
  }),
  patternRule({
    id: 'npm-auth',
    category: 'permission',
    score: 84,
    patterns: [re(NPM + 'code E(?:401|403)(?: |$)'), re(NPM + '(?:401|403) .*(?:Unauthorized|Forbidden)'), re(NPM + 'need auth'), /Unable to authenticate, need: /],
    title: 'npm registry authentication/authorization failed (401/403)',
    explanation: 'The registry rejected the request: the token is missing, expired, or lacks permission for this package/scope.',
    suggestions: [
      'Check that the token secret exists in this repository/environment (secrets are not available to workflows from forks).',
      'Check the scope and registry URL in .npmrc / setup-node registry-url, and that the token has the needed access.',
    ],
    after: 2,
  }),
  patternRule({
    id: 'npm-integrity',
    category: 'npm',
    score: 82,
    patterns: [re(NPM + 'code EINTEGRITY'), /integrity checksum failed/i, /Integrity check failed/],
    title: 'npm integrity checksum mismatch (EINTEGRITY)',
    explanation: 'A downloaded tarball does not match the hash in the lockfile: a corrupted cache, a republished version, or a mirror serving different content.',
    suggestions: ['Clear the npm/actions cache for this job and retry.', 'If it persists, regenerate the lockfile entry for that package.'],
    after: 2,
  }),
  patternRule({
    id: 'npm-missing-package-json',
    category: 'npm',
    score: 86,
    patterns: [re(NPM + 'enoent (?:Could not read package[.]json|ENOENT: no such file or directory, open .*package[.]json)'), /Could not read package\.json/],
    title: 'package.json not found in the working directory',
    explanation: 'npm ran in a directory that has no package.json: wrong working-directory, or the repository was not checked out.',
    suggestions: ['Add actions/checkout before this step.', 'Set working-directory on the step (or cd) to the folder containing package.json.'],
  }),
  patternRule({
    id: 'npm-missing-script',
    category: 'npm',
    score: 86,
    patterns: [re(NPM + 'Missing script: "?([A-Za-z0-9:._-]+)"?'), /^error Command "([A-Za-z0-9:._-]+)" not found[.]/],
    title: (m) => 'npm script not defined: ' + (m[1] ?? ''),
    explanation: 'The workflow runs "npm run <script>" but package.json has no such script.',
    suggestions: ['Add the script to package.json or correct the name in the workflow.', 'Check the working-directory if the project is in a subfolder (monorepo).'],
  }),
  patternRule({
    id: 'frozen-lockfile',
    category: 'npm',
    score: 92,
    patterns: [
      /ERR_PNPM_OUTDATED_LOCKFILE/,
      /Cannot install with "frozen-lockfile" because pnpm-lock\.yaml is not up to date/,
      /The lockfile would have been modified by this install, which is explicitly forbidden/,
      /Your lockfile needs to be updated, but yarn was run with/,
      /error Your lockfile needs to be updated/,
    ],
    title: 'Lockfile is out of date (frozen-lockfile install refused)',
    explanation: 'The package manager was told not to change the lockfile, but package.json requires changes to it.',
    suggestions: ['Run the install locally (pnpm install / yarn install), commit the updated lockfile.'],
    after: 2,
  }),
  patternRule({
    id: 'engine-incompatible',
    category: 'npm',
    score: 80,
    patterns: [
      /^error .*The engine "node" is incompatible with this module\. Expected version "(.+?)"\. Got "(.+?)"/,
      /ERR_PNPM_UNSUPPORTED_ENGINE/,
      /^npm (?:ERR!|error) code EBADENGINE/,
    ],
    title: (m) => 'Node version does not satisfy a package "engines" requirement' + (m[1] ? ' (needs ' + m[1] + ', got ' + m[2] + ')' : ''),
    explanation: 'A dependency (or your project) declares a Node.js version range and the job runs a different version.',
    suggestions: ['Set node-version in actions/setup-node to a version in the required range.', 'Or pin a dependency version compatible with the Node version you run.'],
    after: 3,
  }),
  patternRule({
    id: 'node-gyp-build',
    category: 'npm',
    score: 72,
    patterns: [/^(?:npm (?:ERR!|error) )?gyp ERR! (?:stack Error|build error)/],
    title: 'A native module failed to build (node-gyp)',
    explanation: 'A dependency needs compiling and the build failed: usually a missing compiler/Python/system library or an unsupported Node version for that package version.',
    suggestions: ['Look at the compiler error above the gyp lines.', 'Upgrade the package to a version with prebuilt binaries for this Node version, or install the build prerequisites on the runner.'],
    before: 2,
  }),
  patternRule({
    id: 'npm-lifecycle',
    category: 'npm',
    kind: 'symptom',
    score: 30,
    patterns: [re(NPM + 'code ELIFECYCLE'), re(NPM + 'Test failed[.] See above for more details')],
    title: 'An npm script exited with a non-zero status (ELIFECYCLE)',
    explanation: 'npm only reports that the script failed; the actual error is printed earlier in the log.',
    suggestions: ['Look at the output above the "npm ERR!" block for the real error.'],
    pick: 'last',
  }),
];
