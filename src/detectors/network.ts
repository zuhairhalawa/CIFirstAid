import { patternRule } from './rule.js';

export const networkRules = [
  patternRule({
    id: 'rate-limit',
    category: 'rate-limit',
    score: 90,
    patterns: [
      /API rate limit exceeded/i,
      /secondary rate limit/i,
      /(?:You have|have) exceeded (?:a|the) (?:secondary )?rate limit/i,
      /rate limit (?:exceeded|reached|hit)/i,
      /toomanyrequests/i,
      /You have reached your (?:pull|unauthenticated pull) rate limit/i,
      /429 Too Many Requests/i,
      /(?:HTTP(?:[/][\d.]+)?|status(?: code)?:?) 429(?:\b)/i,
      /npm (?:ERR!|error) code E429/,
      /Throttling: Rate exceeded|RateLimitExceeded|TooManyRequestsException/,
    ],
    title: (m) => (/pull rate limit|toomanyrequests/i.test(m[0]) ? 'Docker registry pull rate limit hit' : 'Rate limit exceeded (HTTP 429 / API limit)'),
    explanation: 'The service throttled the job for making too many requests. Unauthenticated or shared-IP requests hit limits sooner.',
    suggestions: [
      'Authenticate the request (GITHUB_TOKEN for GitHub API calls, docker login for Docker Hub) to get higher limits.',
      'Cache downloads/dependencies, reduce parallel jobs hitting the same service, and add retry with backoff.',
      'For GitHub secondary limits wait a few minutes before re-running.',
    ],
    before: 1,
  }),
  patternRule({
    id: 'localhost-refused',
    category: 'network',
    score: 82,
    patterns: [/ECONNREFUSED (?:127[.]0[.]0[.]1|::1|localhost)[:\s]*(\d+)?/, /connect: connection refused.*(?:127[.]0[.]0[.]1|localhost)/i, /Connection refused.*(?:127[.]0[.]0[.]1|localhost)/i, /could not connect to server: Connection refused/],
    title: (m) => 'Connection refused to a local service' + (m[1] ? ' on port ' + m[1] : ''),
    explanation:
      'Something tried to connect to a service on this runner and nothing was listening: the service container/server has not started yet, crashed, or listens on a different port/host.',
    suggestions: [
      'Wait for readiness before running tests (health-check on a service container, wait-on / pg_isready).',
      'Check the service container port mapping and the host name: in a container job use the service name, not localhost.',
    ],
    before: 1,
  }),
  patternRule({
    id: 'dns-failure',
    category: 'network',
    score: 74,
    patterns: [
      /getaddrinfo (?:ENOTFOUND|EAI_AGAIN) (\S+)/,
      /Could not resolve host: (\S+)/,
      /Temporary failure in name resolution/,
      /Name or service not known/,
      /no such host/,
      /(?:\bENOTFOUND\b) (\S+)/,
    ],
    title: (m) => 'DNS lookup failed' + (m[1] ? ' for ' + m[1] : ''),
    explanation: 'The runner could not resolve a host name: a typo in the URL, a private/internal host not reachable from GitHub-hosted runners, or a transient DNS outage.',
    suggestions: ['Check the host name is correct and publicly resolvable from the runner.', 'If transient, re-run; add retries around network-dependent steps.'],
  }),
  patternRule({
    id: 'tls-failure',
    category: 'network',
    score: 76,
    patterns: [
      /UNABLE_TO_VERIFY_LEAF_SIGNATURE|CERT_HAS_EXPIRED|DEPTH_ZERO_SELF_SIGNED_CERT|SELF_SIGNED_CERT_IN_CHAIN|ERR_TLS_CERT_ALTNAME_INVALID/,
      /unable to verify the first certificate/,
      /self[- ]signed certificate/,
      /SSL certificate problem/,
      /certificate verify failed/,
      /x509: certificate/,
    ],
    title: 'TLS certificate verification failed',
    explanation: 'The server certificate was rejected: expired, self-signed, issued for another host, or missing from the trust store (common with internal registries/proxies).',
    suggestions: ['Check the certificate on the target host; trust the internal CA on the runner if it is a private service.', 'Do not disable verification (NODE_TLS_REJECT_UNAUTHORIZED=0) except as a temporary diagnostic.'],
  }),
  patternRule({
    id: 'connection-error',
    category: 'network',
    score: 68,
    patterns: [
      /(?:\bECONNRESET\b)/,
      /(?:\bETIMEDOUT\b)/,
      /(?:\bECONNREFUSED\b)/,
      /(?:\bEHOSTUNREACH\b|\bENETUNREACH\b)/,
      /socket hang up/,
      /Connection timed out/i,
      /Connection reset by peer/i,
      /Connection refused/i,
      /Network is unreachable/i,
      /TLS handshake timeout/,
      /curl: \((?:7|28|35|52|55|56)\)/,
      /Read timed out|Remote end closed connection|RemoteDisconnected/,
      /tcp [\d.:]+: i[/]o timeout/,
    ],
    title: (m) => 'Network error while contacting a remote service (' + m[0].slice(0, 60) + ')',
    explanation: 'A connection to a remote host failed or was cut. These are frequently transient, but can also mean a blocked/unreachable endpoint or an overloaded service.',
    suggestions: ['Re-run once to see if it is transient; if it repeats, test the endpoint from a runner shell step.', 'Add retries with backoff around downloads (npm: fetch-retries; curl: --retry).'],
    before: 1,
  }),
  patternRule({
    id: 'upstream-5xx',
    category: 'network',
    score: 66,
    patterns: [
      /(?:HTTP(?:[/][\d.]+)?|status(?: code)?:?|error:?) 50[0234](?:\b)/i,
      /(?:\b50[234] (?:Bad Gateway|Service Unavailable|Gateway Time-?out))/i,
      /Something went wrong while executing your query/,
      /Internal Server Error/,
    ],
    title: 'A remote service returned a server error (5xx)',
    explanation: 'The remote side failed, not your code: the service (package registry, GitHub API, a download host) had an outage or a transient error.',
    suggestions: ['Check the provider status page and re-run the job.', 'Add retries with backoff around the failing call.'],
    before: 1,
  }),
];
